/**
 * Разбор ошибки для показа человеку и для поддержки.
 *
 * Фронт-ТЗ, раздел 3: «request_id показывается в technical error details
 * для поддержки». Бэкенд протаскивает его сквозь весь стек и возвращает
 * в каждой ошибке, клиент его разбирает — и до сих пор ни один экран его
 * не показывал. Идентификатор, который никому не виден, не помогает найти
 * запрос в логах, а ради этого он и существует.
 *
 * Второе, что здесь решается: **не всякая ошибка приходит от бэкенда**.
 * Обрыв связи роняет `fetch` обычным `TypeError`, и экраны, приводившие
 * ошибку к `ApiError`, показывали оператору английское «Failed to fetch»
 * посреди русского кабинета.
 */

import { ApiError } from '@/api/client'

/** Одна строка технических подробностей: подпись и значение. */
export interface ErrorDetail {
  label: string
  value: string
}

const NETWORK = 'Не удалось связаться с сервером. Проверьте соединение и повторите.'
const UNKNOWN = 'Не удалось выполнить запрос'

/**
 * Текст для человека, по-русски и всегда.
 *
 * Сообщение бэкенда уже на русском (единый формат ошибки), поэтому оно
 * идёт как есть. Всё остальное подменяется: браузерное «Failed to fetch»
 * оператору не говорит ничего и выглядит поломкой кабинета, а не сети.
 */
export function errorMessage(error: unknown): string {
  if (error instanceof ApiError) return error.message
  if (error instanceof TypeError) return NETWORK
  // Строка сюда попадает только от нас: браузер и библиотеки бросают
  // объекты, а не строки. Это наши собственные сообщения проверки формы
  // («Введите шесть цифр»), и подменять их общим текстом значило бы
  // спрятать единственную подсказку, которая человеку и нужна.
  if (typeof error === 'string' && error.trim()) return error
  return UNKNOWN
}

/**
 * Подробности для поддержки. Пустой список — показывать нечего.
 *
 * Порядок от полезного к служебному: по идентификатору запроса поддержка
 * находит запись в логах, код ошибки отвечает «что случилось», код HTTP —
 * «на каком уровне». Ошибка без идентификатора тоже даёт строки: код
 * и статус сужают поиск, когда сам запрос до сервера не дошёл.
 */
export function technicalDetails(error: unknown): ErrorDetail[] {
  if (!(error instanceof ApiError)) return []
  const details: ErrorDetail[] = []
  if (error.requestId) details.push({ label: 'Идентификатор запроса', value: error.requestId })
  details.push({ label: 'Код ошибки', value: error.code })
  details.push({ label: 'Код HTTP', value: String(error.status) })
  // Поле формы — не техническая деталь, а подсказка, где искать: она уже
  // видна рядом с полем, поэтому сюда не дублируется.
  return details
}

/**
 * Одна строка для копирования в обращение к поддержке.
 *
 * Копируется целиком, а не по одному значению: человек, читающий
 * идентификатор с экрана вслух, ошибётся в нём с первого раза.
 */
export function detailsToText(error: unknown): string {
  return technicalDetails(error)
    .map((detail) => `${detail.label}: ${detail.value}`)
    .join('\n')
}
