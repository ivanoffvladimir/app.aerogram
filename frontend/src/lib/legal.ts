/**
 * Тексты юридических документов кабинета.
 *
 * Данными, а не разметкой, по двум причинам. Править их будет юрист, а не
 * разработчик, и одна структура вместо десятка тегов делает правку
 * возможной без знания React. И у документа есть версия и дата — они обязаны
 * жить рядом с текстом, иначе однажды поменяется текст, а версия останется
 * прежней, и сослаться на редакцию, действовавшую в марте, будет нечем.
 *
 * ВНИМАНИЕ. Тексты — ЧЕРНОВИК, выведенный из описи
 * `docs/legal/personal-data-inventory.md`. Опись снята чтением кода
 * и фактически верна: перечисленные получатели данных — те самые, кому код
 * их действительно отправляет. Юридической проверки тексты не проходили,
 * и до неё публиковать их как действующие нельзя.
 */

export interface LegalSection {
  heading: string
  /** Абзацы. Пустой массив допустим, если весь раздел — список. */
  body?: string[]
  items?: string[]
}

export interface LegalDocument {
  slug: 'privacy' | 'consent'
  title: string
  /** Редакция документа. Меняется вместе с любым изменением текста. */
  version: string
  effectiveFrom: string
  sections: LegalSection[]
}

